const CATEGORY_TO_TOPIC_KEY = new Map<string, string>(
  BLOG_TOPICS.map((t) => [t.legacyCategory.toLowerCase(), t.key])
);

export function getBlogUi(lang: string): BlogLocaleUi {
  return BLOG_UI[lang] || BLOG_UI.en;
}

export function resolveBlogTopicKey(blogTopic?: string, legacyCategory?: string): string {
  if (blogTopic && BLOG_TOPICS.some((t) => t.key === blogTopic)) return blogTopic;
  if (legacyCategory) {
    const mapped = CATEGORY_TO_TOPIC_KEY.get(legacyCategory.trim().toLowerCase());
    if (mapped) return mapped;
  }
  return 'supply-chain-sourcing';
}

export function getTopicTitle(topicKey: string, lang: string): string {
  const found = BLOG_TOPICS.find((t) => t.key === topicKey);
  return found?.titles[lang] || found?.titles.en || topicKey;
}

export function getSubtopicTitle(topicKey: string, subtopicKey: string, lang: string): string {
  const topic = BLOG_TOPICS.find((t) => t.key === topicKey);
  const sub = topic?.subtopics.find((s) => s.key === subtopicKey);
  return sub?.titles[lang] || sub?.titles.en || subtopicKey;
}
